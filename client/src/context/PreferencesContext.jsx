export function PreferencesProvider({ children }) {
  const [language, setLanguage] = useState(() => localStorage.getItem('classmind-language') || 'en');
  const [theme, setTheme] = useState(() => localStorage.getItem('classmind-theme') || 'light');

  useEffect(() => {
    localStorage.setItem('classmind-language', language);
    document.documentElement.lang = language;
  }, [language]);

  useEffect(() => {
    localStorage.setItem('classmind-theme', theme);
    document.documentElement.dataset.theme = theme;
  }, [theme]);

  const value = {
    language,
    theme,
    setLanguage,
    setTheme,
    toggleTheme: () => setTheme((current) => current === 'light' ? 'dark' : 'light'),
    t: (key) => translations[language][key] || translations.en[key] || key,
  };

  return <PreferencesContext.Provider value={value}>{children}</PreferencesContext.Provider>;
}

export function usePreferences() {
  return useContext(PreferencesContext);
}
